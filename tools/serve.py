"""Launch Eric Da Red: scan the Music folder, start a local web server, open the browser."""
import http.server
import json
import os
import socketserver
import sys
import threading
import webbrowser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

AUDIO_EXT = ('.mp3', '.ogg', '.wav', '.m4a', '.aac', '.flac', '.webm')


def write_music_manifest():
    files = []
    for folder in ('Music', 'Music_Tracks', 'music'):
        d = os.path.join(ROOT, folder)
        if os.path.isdir(d):
            files += [folder + '/' + f for f in sorted(os.listdir(d)) if f.lower().endswith(AUDIO_EXT)]
    with open(os.path.join(ROOT, 'js', 'music_manifest.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Auto-generated by tools/serve.py - lists the files found in Music/.\n')
        fh.write('window.MUSIC_FILES = ' + json.dumps(files) + ';\n')
    print('Music found:', ', '.join(files) if files else '(none - drop songs into the Music folder)')


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map,
                      '.js': 'text/javascript', '.woff2': 'font/woff2', '.mp4': 'video/mp4', '.m4a': 'audio/mp4'}

    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        super().end_headers()

    def log_message(self, *args):
        pass


def main():
    write_music_manifest()
    for port in range(8642, 8662):
        try:
            httpd = socketserver.ThreadingTCPServer(('127.0.0.1', port), Handler)
            break
        except OSError:
            continue
    else:
        print('Could not find a free port.')
        sys.exit(1)
    url = f'http://127.0.0.1:{port}/'
    print(f'Eric Da Red is running at {url}  (close this window to stop)')
    if '--no-browser' not in sys.argv:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()
    httpd.serve_forever()


if __name__ == '__main__':
    main()
